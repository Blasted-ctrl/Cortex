import { existsSync } from 'node:fs'
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises'
import { basename, join, resolve } from 'node:path'
import { sha256 } from '../runner'

const LAYER_FILES = ['cortex_hil.h', 'cortex_hil_main.h'] as const

/**
 * The C++ sources for the board live beside this module in the source tree. Compiled
 * JavaScript runs from out/firmware/..., so look for the checkout's copy as well.
 */
export function deviceDirectory(): string {
  const candidates = [
    resolve(__dirname, 'device'),
    resolve(__dirname, '..', '..', '..', '..', '..', 'src', 'main', 'firmwareTesting', 'hil', 'device'),
    resolve('src', 'main', 'firmwareTesting', 'hil', 'device')
  ]
  return candidates.find((dir) => existsSync(join(dir, 'cortex_hil.h'))) ?? candidates[0]
}

/** The generated sketch: the layer, then the firmware byte for byte, then the real setup/loop. */
export function hilSketchSource(firmwareSource: string, firmwarePath: string): string {
  return [
    `// Generated by the Cortex HIL harness from ${basename(firmwarePath)}. Do not edit; regenerate.`,
    '#include "cortex_hil.h"',
    `#line 1 "${firmwarePath.replace(/\\/g, '/')}"`,
    firmwareSource.replace(/\s*$/, ''),
    '#include "cortex_hil_main.h"',
    ''
  ].join('\n')
}

export interface HilSketch {
  sketchDir: string
  sourceSha256: string
  layerSha256: string
  sketchSha256: string
}

/** Arduino requires the folder and the .ino to share a name. */
export async function writeHilSketch(firmwarePath: string, parentDir: string): Promise<HilSketch> {
  if (!/\.ino$/i.test(firmwarePath)) throw new Error('The HIL harness builds a .ino sketch')
  const source = await readFile(firmwarePath, 'utf8')
  const sketchDir = join(parentDir, 'cortex_hil_sketch')
  await mkdir(sketchDir, { recursive: true })
  const sketch = hilSketchSource(source, firmwarePath)
  await writeFile(join(sketchDir, 'cortex_hil_sketch.ino'), sketch, 'utf8')
  let layer = ''
  for (const file of LAYER_FILES) {
    const from = join(deviceDirectory(), file)
    await copyFile(from, join(sketchDir, file))
    layer += await readFile(from, 'utf8')
  }
  return { sketchDir, sourceSha256: sha256(source), layerSha256: sha256(layer), sketchSha256: sha256(sketch) }
}
